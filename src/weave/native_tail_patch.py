def packed_offsets(expert, n_tile, n, k, tile_n):
    """First packed-weight and E8M0-scale int4 offsets for a native N tile."""
    if expert < 0 or min(n, k, tile_n) <= 0 or n % tile_n or k % 32 or not 0 <= n_tile < n // tile_n:
        raise ValueError('invalid MXFP4 packed tile geometry')
    return expert * n * k // 32 + n_tile * tile_n // 2, expert * n * k // 512 + n_tile * tile_n // 16


def audit_task_coverage(sorted_ids, experts, padded, pair_rows, n, block_size, tile_n, *, num_experts):
    """Private diagnostic: grouping validity and exact pair/channel task cover."""
    if block_size not in (8, 16, 32, 48, 64) or n <= 0 or n % tile_n or pair_rows < 0:
        raise ValueError('invalid native task geometry')
    if padded < 0 or padded % block_size or padded > len(sorted_ids) or padded // block_size > len(experts):
        raise ValueError('invalid padded group count')
    seen, local_pairs, local_groups, tasks = set(), 0, 0, []
    for group in range(padded // block_size):
        expert = experts[group]
        if expert < -1 or expert >= num_experts:
            raise ValueError('invalid native expert id')
        padding = False
        local_groups += expert >= 0
        for slot in sorted_ids[group * block_size:(group + 1) * block_size]:
            if slot < 0:
                raise ValueError('negative pair slot')
            if slot >= pair_rows:
                padding = True
                continue
            if padding or slot in seen:
                raise ValueError('misplaced padding or duplicate pair slot')
            seen.add(slot)
            local_pairs += expert >= 0
        if expert >= 0:
            tasks.extend(group * (n // tile_n) + col for col in range(n // tile_n))
    if seen != set(range(pair_rows)):
        raise ValueError('incomplete pair slot coverage')
    return dict(valid_pairs=local_pairs, local_groups=local_groups, local_tasks=len(tasks),
                covered_elements=local_pairs * n, expected_task_ids=tasks)


def extract_static_host(source):
    """Keep the native register-aware candidate selection; measure new binary."""
    _verify(HOST, source.encode())
    start = source.index('typedef struct {\n  int thread_k;')
    end = source.index('template <typename scalar_t, bool kIsEP, bool kHasBias>\nMarlinFuncPtr get_marlin_kernel')
    policy = source[start:end].replace('kernel = Marlin<', 'kernel = StaticMarlin<')
    choose = _region(source,
        'template <typename scalar_t, bool kIsEP, bool kHasBias>\nexec_config_t determine_exec_config',
        'template <typename scalar_t, bool kIsEP, bool kHasBias>\nvoid marlin_mm')
    return '''#pragma once
#include <sgl_kernel/tensor.h>
#include "marlin_down_tile.cuh"
namespace weave::native_tail {
using namespace device::marlin;
using namespace host;
using MarlinFuncPtr = void (*)(DownTileArgs, int64_t*, int*, int);
__global__ void MarlinDefault(DownTileArgs, int64_t*, int*, int) {}
template<typename scalar_t, host::ScalarTypeId W, host::ScalarTypeId S,
         int Threads,int M,int N,int K,bool M8,int Stages,int Groups,
         bool ZP,bool EP,bool Bias>
__global__ void StaticMarlin(DownTileArgs args, int64_t* visits, int* error, int scratch_bytes) {
  extern __shared__ int4 scratch[];
  constexpr int block_rows = M8 ? 8 : 16 * M;
  const int tiles = args.n / (16 * N);
  const int padded = *args.num_tokens_padded;
  if (padded < 0 || padded % block_rows || padded > args.group_capacity * block_rows) {
    if (threadIdx.x == 0) atomicOr(error, 1);
    return;
  }
  // Static task striding is solely a scratch-reuse probe; no work queue.
  for (int task = blockIdx.x; task < args.group_capacity * tiles; task += gridDim.x) {
  const int group = task / tiles, tile = task % tiles;
  if (group >= padded / block_rows) break;
  const int expert = args.expert_ids[group];
  if (expert < -1 || expert >= args.num_experts) {
    if (threadIdx.x == 0) atomicOr(error, 2);
    return;
  }
  // A task may read only valid prefix rows, followed by padding sentinels.
  __shared__ int bad;
  if (threadIdx.x == 0) bad = 0;
  __syncthreads();
  if (threadIdx.x < block_rows) {
    const int offset = group * block_rows + threadIdx.x;
    const int slot = args.sorted_token_ids[offset];
    if (slot < 0 || (threadIdx.x && slot < args.pair_rows &&
        args.sorted_token_ids[offset - 1] >= args.pair_rows)) atomicOr(&bad, 4);
  }
  __syncthreads();
  if (bad) { if (threadIdx.x == 0) atomicOr(error, bad); return; }
  if (expert == -1) continue;
  run_marlin_down_tile<Threads,M,N,K,M8,Stages>(args,group,tile,scratch,scratch_bytes);
  if (threadIdx.x == 0 && visits) atomicAdd(
      reinterpret_cast<unsigned long long*>(visits + task), 1ULL);
  }
}
''' + policy + '''
template<typename scalar_t,bool kIsEP,bool kHasBias>
MarlinFuncPtr get_marlin_kernel(const host::ScalarType q_type, int thread_m_blocks,
    int thread_n_blocks,int thread_k_blocks,bool m_block_size_8,bool has_act_order,
    bool has_zp,int group_blocks,int num_threads,bool is_zp_float) {
  auto kernel = MarlinDefault;
  if (false) {}
  MXFP4_GET_IF(host::kFE2M1f)
  return kernel;
}
''' + choose + (ROOT / 'experimental/native_tail/down_static_binding.cuh').read_text()


def build_overlay(package_root, cache_root):
    package_root, cache_root = Path(package_root), Path(cache_root)
    pins = verify_sources(package_root)
    helper = extract_down_header((package_root / TEMPLATE).read_text())
    committed = ROOT / 'experimental/native_tail/marlin_down_tile.cuh'
    if committed.read_text() != helper:
        raise RuntimeError('generated Marlin down helper differs from committed extraction')
    host = extract_static_host((package_root / HOST).read_text())
    digest = hashlib.sha256(json.dumps(pins, sort_keys=True).encode() + helper.encode() + host.encode())
    identity = digest.hexdigest()
    overlay = cache_root / ('native-tail-' + identity)
    for name in pins:
        if name.startswith('kernels/jit/'):
            target = overlay / name
            target.parent.mkdir(parents=True, exist_ok=True)
            raw = (package_root / name).read_bytes()
            if not target.exists() or target.read_bytes() != raw:
                target.write_bytes(raw)
    directory = overlay / PREFIX
    for name, content in (('marlin_down_tile.cuh', helper), ('down_static.cuh', host)):
        path = directory / name
        if not path.exists() or path.read_text() != content:
            path.write_text(content)
    return dict(header=directory / 'down_static.cuh', helper_header=directory / 'marlin_down_tile.cuh',
                include_dirs=[str(overlay / 'kernels/jit/include')], overlay_sha256=identity)


def load_down_op(package_root, cache_root):
    """Compile lazily in the existing SGLang image. prepare() runs before capture."""
    import torch
    from sglang.kernels.jit.utils import load_jit
    overlay = build_overlay(package_root, cache_root)
    module = load_jit('weave_native_tail_down_' + overlay['overlay_sha256'],
                      external_cuda_files=[str(overlay['header'])],
                      extra_include_paths=overlay['include_dirs'],
                      cuda_wrappers=[('configure', 'weave::native_tail::configure_down'),
                                     ('run', 'weave::native_tail::launch_down')])

    @lru_cache(None)
    def prepare(pair_rows, n, k, block_size, device_index):
        config = torch.empty(16, dtype=torch.int64, device='cpu')
        module.configure(pair_rows, n, k, block_size, device_index, config)
        names = ('threads', 'm_blocks', 'n_blocks', 'k_blocks', 'm8', 'stages',
                 'scratch_bytes', 'registers', 'static_shared_bytes', 'local_bytes',
                 'active_blocks_per_sm', 'sms', 'native_selected_blocks_per_sm',
                 'max_threads_per_block', 'binary_version', 'ptx_version')
        return dict(zip(names, config.tolist()))

    def op(activation, w2, scales, sorted_ids, expert_ids, padded, topk_weights, output,
           moe_block_size, *, visits=None, error, geometry=None, grid_workers=0):
        n, k = output.shape[1], activation.shape[1]
        if activation.dtype != torch.bfloat16 or scales.dtype != torch.float8_e8m0fnu:
            raise ValueError('native tail down requires original BF16 activation/E8M0 scales')
        if w2.dtype != torch.int32:
            raise ValueError('native repacked MXFP4 weights must be int32')
        geometry = geometry or prepare(activation.shape[0], n, k, moe_block_size, activation.device.index)
        if visits is None:
            # Empty diagnostic storage is preallocated/captured by the caller.
            raise ValueError('pass a preallocated visits tensor (empty disables diagnostics)')
        module.run(activation, w2, scales, sorted_ids, expert_ids, padded,
                   topk_weights, output, visits, error, moe_block_size,
                   geometry['threads'], geometry['n_blocks'], geometry['k_blocks'],
                   geometry['scratch_bytes'], grid_workers)
        return output

    op.prepare = prepare
    op.weave_overlay_sha256 = overlay['overlay_sha256']
    op.helper_header = overlay['helper_header']
    op.include_dirs = overlay['include_dirs']
    op.module = module
    return op
